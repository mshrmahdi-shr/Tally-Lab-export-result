"""Regenerate the empty R2004 DXF template. Dev only: pip install ezdxf==1.4.4."""
import io, json
from pathlib import Path
import ezdxf
from ezdxf.entities import factory
from ezdxf.lldxf.extendedtags import ExtendedTags

doc = ezdxf.new('R2004')
for key,value in {'$INSUNITS':0,'$MEASUREMENT':1,'$LWDISPLAY':False,'$FILLMODE':1}.items(): doc.header[key]=value
doc.layers.new('MAGIC_TABLES', dxfattribs={'color':7,'lineweight':-3})
doc.styles.new('MAGIC_Arial', dxfattribs={'font':'arial.ttf'})
for name in ('ACAD_TABLE','TABLESTYLE'): doc.classes.add_class(name)
d = doc.rootdict.get_required_dict('ACAD_TABLESTYLE')
sh = doc.entitydb.next_handle()
tags=[(0,'TABLESTYLE'),(5,sh),(330,d.dxf.handle),(100,'AcDbTableStyle'),(3,'MAGIC Detailed'),(70,0),(71,0),(40,.9),(41,.5),(280,0),(281,1)]
for i,size in enumerate((2.5,2.8,2.5)):
    tags += [(7,'MAGIC_Arial'),(140,size),(170,5),(62,250),(63,51 if i==1 else 255),(283,1)]
    for k in range(6): tags += [(274+k,-3),(284+k,1),(64+k,250)]
e=factory.load(ExtendedTags.from_text(''.join(f'{c}\n{v}\n' for c,v in tags)),doc)
doc.entitydb.add(e);doc.objects.add_object(e);d['MAGIC Detailed']=e
s=io.StringIO();doc.write(s)
lines=s.getvalue().splitlines()
pairs=[[int(lines[i]),lines[i+1]] for i in range(0,len(lines),2)]
# The runtime fills the symbol table, graphics blocks and modelspace dynamically.
base={'pairs':pairs,'styleHandle':sh,'modelHandle':doc.modelspace().block_record_handle}
p=Path(__file__).resolve().parent.parent/'native-dxf-base.js'
p.write_text('// Empty DXF structure generated by scripts/build-dxf-base.py (ezdxf MIT). No project data.\n(function(root){\nconst base='+json.dumps(base,separators=(',',':'))+';\nif(typeof module!=="undefined" && module.exports) module.exports=base; else root.TallyDxfBase=base;\n})(globalThis);\n')
print(p)
