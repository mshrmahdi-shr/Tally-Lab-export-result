function magicCsvDxfLispQuote(value){
 const safe=String(value??"").replace(/\\/g,"\\\\").replace(/\{/g,"\\{").replace(/\}/g,"\\}").replace(/\r\n|\r|\n/g,"\\P");
 return '"'+safe.replace(/\\/g,"\\\\").replace(/"/g,'\\"')+'"';
}

function magicCsvDxfLispList(items){return "(list "+items.join(" ")+")";}

function magicCsvDxfNativeRows(rows,mode){
 const q=magicCsvDxfLispQuote, t=x=>x?"T":"nil";
 return rows.map(r=>{
   if(mode==="summary")return magicCsvDxfLispList([q("summary"),q(r.sample),q(r.note),q(r.depth),q(r.analyses),q(r.result),t(r.exceeded)]);
   if(r.role==="sampleSummary")return magicCsvDxfLispList([q("sampleSummary"),q(r.sample),q(r.note),q(r.depth),q(r.analyses),q(r.exceededGroups),String(Math.max(1,Math.floor(Number(r.sampleSpan)||1))),t(r.exceeded)]);
   return magicCsvDxfLispList([q("detail"),q(r.group),magicCsvDxfLispList((r.parameters||[]).map(q)),magicCsvDxfLispList((r.results||[]).map(q)),magicCsvDxfLispList((r.standards||[]).map(q)),t(r.exceeded)]);
 });
}

function magicCsvDxfNativeDate(value,fullDate){
 const s=String(value||"");
 if(!fullDate||!/^\d{4}-\d{2}-\d{2}$/.test(s))return s;
 const [year,month,day]=s.split("-").map(Number);
 const names=["January","February","March","April","May","June","July","August","September","October","November","December"];
 return month>=1&&month<=12&&day>=1&&day<=31 ? day+" "+names[month-1]+" "+year : s;
}

function magicCsvDxfBuildNativeLisp(models,options={}){
 if(!Array.isArray(models)||!models.length)throw Error("Load a valid CSV/TSV file first.");
 const q=magicCsvDxfLispQuote;
 const fullDate=options.fullDate!==false;
 const widths=options.referenceLayout===false?[36,68,24,24]:[27.54,58,16,16];
 const rgb=options.titleFill==="groundwater"?[204,255,255]:options.titleFill==="white"?[255,255,255]:[255,236,179];
 const data=magicCsvDxfLispList(models.map(m=>{
   const title=String(m.bh||"Borehole")+(m.date?" ("+magicCsvDxfNativeDate(m.date,fullDate)+")":"");
   return magicCsvDxfLispList([q(title),q(m.mode),magicCsvDxfLispList(magicCsvDxfNativeRows(m.rows||[],m.mode))]);
 }));
 const prefix=String.raw`;;; MAGIC CSV Native AutoCAD Table Exporter V1.0
;;; One-time AutoLISP generated by the Tally website.
;;; APPLOAD this file in AutoCAD LT 2024+, AutoCAD or Civil 3D.
;;; Creates genuine AcDbTable objects (not LINE/TEXT geometry).
;;; Commands: MAGICCSVIMPORT / MAGICCSV
(vl-load-com)
(defun MAGICCSV:safe (fn args / result)
  (setq result (vl-catch-all-apply fn args))
  (if (vl-catch-all-error-p result) nil result)
)
(defun MAGICCSV:rgb-cell (tb r c rgb / color)
  (setq color (MAGICCSV:safe 'vla-get-TrueColor (list tb)))
  (if color
    (progn
      (MAGICCSV:safe 'vla-SetRGB
        (list color (nth 0 rgb) (nth 1 rgb) (nth 2 rgb)))
      (MAGICCSV:safe 'vla-SetCellBackgroundColorNone
        (list tb r c :vlax-false))
      (MAGICCSV:safe 'vla-SetCellBackgroundColor
        (list tb r c color))
      (MAGICCSV:safe 'vlax-release-object (list color))
    )
  )
)
(defun MAGICCSV:join (items separator / result item)
  (setq result "")
  (foreach item items
    (if (and item (/= item ""))
      (setq result
        (if (= result "") item (strcat result separator item)))
    )
  )
  result
)
(defun MAGICCSV:color-red (s)
  (if (= (if s s "") "") ""
    (strcat "{\\C1;" s "}"))
)
(defun MAGICCSV:sample-text (name note depth)
  (strcat (if name name "")
    (if (and note (/= note "")) (strcat "\\P" note) "")
    (if (and depth (/= depth ""))
      (strcat "\\P" (MAGICCSV:color-red (strcat "(" depth ")")))
      "")
  )
)
(defun MAGICCSV:put (tb r c content height)
  (MAGICCSV:safe 'vla-SetText
    (list tb r c (if content content "")))
  (MAGICCSV:safe 'vla-SetCellTextHeight
    (list tb r c height))
  (MAGICCSV:safe 'vla-SetCellAlignment (list tb r c 5))
)
(defun MAGICCSV:rowheight (row / n)
  (if (= (car row) "detail")
    (progn
      (setq n (max 2
        (+ 1 (length (nth 2 row)))
        (length (nth 3 row))
        (length (nth 4 row))))
      (max 12.0 (+ 4.5 (* 4.2 n)))
    )
    12.0
  )
)
(defun MAGICCSV:totalheight (rows / result row)
  (setq result 6.8)
  (foreach row rows (setq result (+ result (MAGICCSV:rowheight row))))
  result
)
(defun MAGICCSV:make-table
  (space pt model / title mode rows n tb r row span col width widths)
  (setq title (nth 0 model)
        mode (nth 1 model)
        rows (nth 2 model)
        n (1+ (length rows))
        widths MAGICCSV:*WIDTHS*)
  (setq tb (MAGICCSV:safe 'vla-AddTable
    (list space (vlax-3d-point pt) n 4 12.0 (nth 0 widths))))
  (if (null tb)
    (progn
      (princ "\nCould not create a native TABLE in this AutoCAD version.")
      nil
    )
    (progn
      (MAGICCSV:safe 'vla-put-RegenerateTableSuppressed
        (list tb :vlax-true))
      (MAGICCSV:safe 'vla-put-Layer (list tb "MAGIC_CAD_TABLES"))
      (setq col 0)
      (foreach width widths
        (MAGICCSV:safe 'vla-SetColumnWidth (list tb col width))
        (setq col (1+ col))
      )
      (MAGICCSV:safe 'vla-SetRowHeight (list tb 0 6.8))
      (setq r 1)
      (foreach row rows
        (MAGICCSV:safe 'vla-SetRowHeight
          (list tb r (MAGICCSV:rowheight row)))
        (setq r (1+ r))
      )
      (MAGICCSV:safe 'vla-MergeCells (list tb 0 0 0 3))
      (MAGICCSV:put tb 0 0 title 2.9)
      (MAGICCSV:rgb-cell tb 0 0 MAGICCSV:*TITLE_RGB*)
      ; Attach white fill to every non-title cell.
      (setq r 1)
      (while (< r n)
        (setq col 0)
        (while (< col 4)
          (MAGICCSV:rgb-cell tb r col '(255 255 255))
          (setq col (1+ col))
        )
        (setq r (1+ r))
      )
      (setq r 1)
      (foreach row rows
        (cond
          ((= (car row) "summary")
            (MAGICCSV:safe 'vla-MergeCells (list tb r r 2 3))
            (MAGICCSV:put tb r 0
              (MAGICCSV:sample-text
                (nth 1 row) (nth 2 row) (nth 3 row)) 2.5)
            (MAGICCSV:put tb r 1 (nth 4 row) 2.35)
            (MAGICCSV:put tb r 2
              (if (nth 6 row)
                (MAGICCSV:color-red (nth 5 row))
                (nth 5 row)) 2.35)
          )
          ((= (car row) "sampleSummary")
            (setq span (nth 6 row))
            (if (> span 1)
              (MAGICCSV:safe 'vla-MergeCells
                (list tb r (min (1- n) (+ r span -1)) 0 0)))
            (MAGICCSV:safe 'vla-MergeCells (list tb r r 2 3))
            (MAGICCSV:put tb r 0
              (MAGICCSV:sample-text
                (nth 1 row) (nth 2 row) (nth 3 row)) 2.5)
            (MAGICCSV:put tb r 1 (nth 4 row) 2.35)
            (MAGICCSV:put tb r 2
              (if (nth 7 row)
                (MAGICCSV:color-red (nth 5 row))
                (nth 5 row)) 2.35)
          )
          ((= (car row) "detail")
            (MAGICCSV:put tb r 1
              (if (nth 5 row)
                (MAGICCSV:color-red
                  (MAGICCSV:join
                    (cons (nth 1 row) (nth 2 row)) "\\P"))
                (MAGICCSV:join
                  (cons (nth 1 row) (nth 2 row)) "\\P"))
              2.25)
            (MAGICCSV:put tb r 2
              (if (nth 5 row)
                (MAGICCSV:color-red
                  (MAGICCSV:join (nth 3 row) "\\P"))
                (MAGICCSV:join (nth 3 row) "\\P"))
              2.25)
            (MAGICCSV:put tb r 3
              (MAGICCSV:join (nth 4 row) "\\P") 2.25)
          )
        )
        (setq r (1+ r))
      )
      (MAGICCSV:safe 'vla-put-HorzCellMargin (list tb 0.7))
      (MAGICCSV:safe 'vla-put-VertCellMargin (list tb 0.3))
      (MAGICCSV:safe 'vla-put-RegenerateTableSuppressed
        (list tb :vlax-false))
      (MAGICCSV:safe 'vla-Update (list tb))
      tb
    )
  )
)
`;
 const suffix=String.raw`
(defun c:MAGICCSVIMPORT (/ doc space pt y model tb made)
  (vl-load-com)
  (setq doc (MAGICCSV:safe 'vla-get-ActiveDocument
    (list (vlax-get-acad-object))))
  (if (null doc)
    (princ "\nAutoCAD document is unavailable.")
    (progn
      (setq pt (getpoint
        "\nChoose upper-left point for the first native table <0,0>: "))
      (if (null pt) (setq pt '(0.0 0.0 0.0)))
      (if (< (length pt) 3)
        (setq pt (append pt '(0.0))))
      (setq space
        (if (= (getvar "CVPORT") 1)
          (vla-get-PaperSpace doc)
          (vla-get-ModelSpace doc)))
      (if (null (tblsearch "LAYER" "MAGIC_CAD_TABLES"))
        (MAGICCSV:safe 'vla-Add
          (list (vla-get-Layers doc) "MAGIC_CAD_TABLES")))
      (MAGICCSV:safe 'vla-StartUndoMark (list doc))
      (setq y (cadr pt) made 0)
      (foreach model MAGICCSV:*TABLES*
        (setq tb (MAGICCSV:make-table
          space (list (car pt) y (caddr pt)) model))
        (if tb
          (progn
            (setq made (1+ made))
            (setq y (- y
              (MAGICCSV:totalheight (nth 2 model)) 12.0))
          )
        )
      )
      (MAGICCSV:safe 'vla-EndUndoMark (list doc))
      (princ (strcat "\nCreated " (itoa made)
        " editable native AutoCAD TABLE object(s)."))
      (princ "\nTABLEEDIT / Properties to edit; SAVEAS to DWG or DXF.")
    )
  )
  (princ)
)
(defun c:MAGICCSV () (c:MAGICCSVIMPORT))
(princ "\nMAGIC CSV Native TABLE Builder V1.0 loaded.")
(c:MAGICCSVIMPORT)
(princ)
`;
 return prefix+
 `(setq MAGICCSV:*WIDTHS* ${magicCsvDxfLispList(widths.map(String))})\n`+
 `(setq MAGICCSV:*TITLE_RGB* ${magicCsvDxfLispList(rgb.map(String))})\n`+
 `(setq MAGICCSV:*TABLES* ${data})\n`+suffix;
}

function magicCsvDxfDownloadNative(){
 const models=magicCsvDxfState.models||[];
 if(!models.length){magicCsvDxfSetMessage("Load a valid MAGIC CSV/TSV first.",true);return;}
 const lsp=magicCsvDxfBuildNativeLisp(models,{
  referenceLayout:document.getElementById("magicCsvDxfReferenceLayout").checked,
  fullDate:document.getElementById("magicCsvDxfFullDate").checked,
  titleFill:document.getElementById("magicCsvDxfTitleFill").value
 });
 const blob=new Blob([lsp],{type:"text/plain;charset=utf-8"});
 const a=document.createElement("a");
 a.href=URL.createObjectURL(blob);
 a.download="MAGIC_CSV_NATIVE_TABLES_V1.0.lsp";
 document.body.appendChild(a);a.click();
 setTimeout(()=>{URL.revokeObjectURL(a.href);a.remove();},1500);
 magicCsvDxfSetMessage("LISP downloaded. APPLOAD it in AutoCAD LT/Civil 3D to create native TABLE objects.");
}

function magicCsvDxfInitNative(){
 const btn=document.getElementById("magicCsvDxfNativeBtn");
 const legacy=document.getElementById("magicCsvDxfExportBtn");
 if(!btn||!legacy)return;
 const sync=()=>{btn.disabled=legacy.disabled;};
 new MutationObserver(sync).observe(legacy,{attributes:true,attributeFilter:["disabled"]});
 sync();
 btn.addEventListener("click",magicCsvDxfDownloadNative);
}
magicCsvDxfInitNative();
